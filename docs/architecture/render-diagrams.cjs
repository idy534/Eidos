async function run() {
  const temporary = await mkdtemp(path.join(os.tmpdir(), "eidos-doc-diagrams-"));
  app.setPath("userData", path.join(temporary, "user-data"));
  let window;
  try {
    await app.whenReady();
    const catalog = JSON.parse(await readFile(path.join(diagramRoot, "catalog.json"), "utf8"));
    const ids = new Set();
    for (const item of catalog) {
      if (!/^\d{2}-[a-z-]+$/.test(item.id) || ids.has(item.id) || !/^[a-z-]+\.md$/.test(item.page)) {
        throw new Error("Invalid or duplicate diagram metadata");
      }
      ids.add(item.id);
      await readFile(path.join(__dirname, item.page), "utf8");
    }
    const mermaid = pathToFileURL(path.join(root, "node_modules/mermaid/dist/mermaid.esm.min.mjs")).href;
    const fixture = path.join(temporary, "render.html");
    await writeFile(fixture, `<html><body><script type="module">import mermaid from ${JSON.stringify(mermaid)};window.mermaid=mermaid;</script></body></html>`);
    window = new BrowserWindow({ show: false, width: 1600, height: 1200,
      webPreferences: { nodeIntegration: false, contextIsolation: true, sandbox: true, partition: "eidos-harness-diagrams" } });
    window.webContents.session.webRequest.onBeforeRequest((details, done) => {
      done({ cancel: !/^(file|data|devtools):/.test(details.url) });
    });
    await window.loadFile(fixture);
    // Module imports may finish after did-finish-load. Bound the local dependency wait.
    for (let attempt = 0; attempt < 100; attempt++) {
      if (await window.webContents.executeJavaScript("Boolean(window.mermaid)")) break;
      if (attempt === 99) throw new Error("Local Mermaid module did not load");
      await new Promise((resolve) => setTimeout(resolve, 50));
    }
    const outputs = [];
    for (const item of catalog) {
      const source = await readFile(path.join(diagramRoot, `${item.id}.mmd`), "utf8");
      const svg = await window.webContents.executeJavaScript(`(async () => {
        mermaid.initialize({startOnLoad:false,securityLevel:"strict",htmlLabels:false,theme:"base",deterministicIds:true,
          deterministicIDSeed:${JSON.stringify(item.id)},fontFamily:"Arial, PingFang SC, sans-serif",
          themeVariables:{primaryColor:"#edf4fa",primaryTextColor:"#193347",primaryBorderColor:"#7194ae",
            lineColor:"#526575",secondaryColor:"#edf6f4",tertiaryColor:"#fbf5e9",fontSize:"16px"},
          flowchart:{htmlLabels:false,curve:"linear",padding:18},sequence:{useMaxWidth:true,wrap:true}});
        await document.fonts.ready;
        const result=await mermaid.render(${JSON.stringify(`diagram-${item.id}`)},${JSON.stringify(source)});
        const doc=new DOMParser().parseFromString(result.svg,"image/svg+xml");
        if(doc.querySelector("parsererror")) throw new Error(${JSON.stringify(item.id)}+": "+doc.querySelector("parsererror").textContent);
        const svg=doc.documentElement;
        const [, , width, height]=svg.getAttribute("viewBox").split(/\\s+/).map(Number);
        svg.setAttribute("width",Math.ceil(width));svg.setAttribute("height",Math.ceil(height));
        const title=doc.createElementNS("http://www.w3.org/2000/svg","title");
        title.id=${JSON.stringify(`title-${item.id}`)};title.textContent=${JSON.stringify(item.title)};
        svg.prepend(title);svg.setAttribute("role","img");svg.setAttribute("aria-labelledby",title.id);
        return new XMLSerializer().serializeToString(svg)+"\\n";
      })()`);
      if (/<foreignObject|<script|(?:href|src)=["']https?:/i.test(svg)) throw new Error(`Nonportable SVG: ${item.id}`);
      const viewBox = svg.match(/\bviewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
      item.minimumWidth = Math.ceil(viewBox[2] * 0.8);
      outputs.push([path.join(diagramRoot, `${item.id}.svg`), svg]);
    }
    outputs.push([path.join(__dirname, "harness-atlas.html"), atlas(catalog)]);
    for (const [file, content] of outputs) {
      if (check) {
        if (await readFile(file, "utf8") !== content) throw new Error(`Stale generated document: ${path.relative(root, file)}`);
      } else {
        await mkdir(path.dirname(file), { recursive: true });
        await writeFile(file, content);
      }
    }
    console.log(`${check ? "Checked" : "Rendered"} ${catalog.length} local diagrams and the offline atlas.`);
  } finally {
    window?.destroy();
    await rm(temporary, { recursive: true, force: true, maxRetries: 6, retryDelay: 100 });
  }
}

run().then(() => app.exit(0)).catch((error) => { console.error(error); app.exit(1); });
