import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.protocol.schemas import ClosedModel, ProjectDto
from eidos_runtime.protocol.git_workspaces import GitWorkspaceContract
from eidos_runtime.protocol.project_workspaces import ProjectReadRequest, ProjectUpdateRequest, ProjectCreateFoldersRequest
class ProjectWorkspaceContract(ClosedModel):
    project: ProjectDto
    git: GitWorkspaceContract
    read_request: ProjectReadRequest
    update_request: ProjectUpdateRequest
    create_request: ProjectCreateFoldersRequest
print(json.dumps(ProjectWorkspaceContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
const banner = "/* Generated by scripts/generate-project-workspace-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/project-workspaces.generated.ts"), await compile(schema, "ProjectWorkspaceContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/project-workspaces-schema.generated.ts"), `${banner}\nexport const projectWorkspacesSchema = ${JSON.stringify(schema, null, 2)};\n`);
