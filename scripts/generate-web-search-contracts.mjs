import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.protocol.web_search import WebSearchReadRequest, WebSearchSaveRequest, WebSearchResponse, WebSearchOfficialPageRequest
class WebSearchContract(EidosFrozenStrictModel):
    read: WebSearchReadRequest
    save: WebSearchSaveRequest
    response: WebSearchResponse
    official_page: WebSearchOfficialPageRequest
print(json.dumps(WebSearchContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8", maxBuffer: 1024 * 1024 }));
const banner = "/* Generated by scripts/generate-web-search-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/web-search.generated.ts"), await compile(schema, "WebSearchContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/web-search-schema.generated.ts"), `${banner}\nexport const webSearchSchema = ${JSON.stringify(schema, null, 2)};\n`);
