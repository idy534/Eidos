import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.models.mcp_details import McpToolsRequest, McpToolsResponse
class McpDetailsContract(EidosFrozenStrictModel):
    request: McpToolsRequest
    response: McpToolsResponse
print(json.dumps(McpDetailsContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
const banner = "/* Generated by scripts/generate-mcp-details-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/mcp-details.generated.ts"), await compile(schema, "McpDetailsContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/mcp-details-schema.generated.ts"), `${banner}\nexport const mcpDetailsSchema = ${JSON.stringify(schema, null, 2)};\n`);
