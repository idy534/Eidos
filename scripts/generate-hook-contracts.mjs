import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenModel
from eidos_runtime.domain.hooks import PluginHookReview, PluginCompatibility
class HookContract(EidosFrozenModel):
    review: PluginHookReview
    compatibility: PluginCompatibility
print(json.dumps(HookContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8", maxBuffer: 1024 * 1024 }));
const banner = "/* Generated by scripts/generate-hook-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/hooks.generated.ts"), await compile(schema, "HookContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/hooks-schema.generated.ts"), `${banner}\nexport const hookSchema = ${JSON.stringify(schema, null, 2)};\n`);
