import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const posixPython = path.join(root, ".venv/bin/python");
const winPython = path.join(root, ".venv/Scripts/python.exe");
const pythonBin = existsSync(posixPython) ? posixPython : winPython;
const schema = JSON.parse(execFileSync(pythonBin, ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.protocol.guardrails import GuardrailsReadRequest, GuardrailsSaveRequest, GuardrailsResponse
class GuardrailsContract(EidosFrozenStrictModel):
    read: GuardrailsReadRequest
    save: GuardrailsSaveRequest
    response: GuardrailsResponse
print(json.dumps(GuardrailsContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8", maxBuffer: 1024 * 1024 }));
const banner = "/* Generated by scripts/generate-guardrails-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/guardrails.generated.ts"), await compile(schema, "GuardrailsContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/guardrails-schema.generated.ts"), `${banner}\nexport const guardrailsSchema = ${JSON.stringify(schema, null, 2)};\n`);
