"""Export the document-skills group as a CPython 3.12/macOS arm64 wheel lock."""
from pathlib import Path
import subprocess
import tomllib
from urllib.parse import unquote, urlsplit

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.tags import compatible_tags, cpython_tags, mac_platforms
from packaging.utils import canonicalize_name, parse_wheel_filename

ROOT = Path(__file__).resolve().parents[1]
IMPORTS = {
    "cffi": "cffi", "charset-normalizer": "charset_normalizer",
    "cryptography": "cryptography", "defusedxml": "defusedxml",
    "et-xmlfile": "et_xmlfile", "lxml": "lxml", "numpy": "numpy",
    "openpyxl": "openpyxl", "pandas": "pandas", "pdfminer-six": "pdfminer",
    "pdfplumber": "pdfplumber", "pillow": "PIL", "pycparser": "pycparser",
    "pypdf": "pypdf", "pypdfium2": "pypdfium2", "python-dateutil": "dateutil",
    "python-docx": "docx", "python-pptx": "pptx", "reportlab": "reportlab",
    "six": "six", "typing-extensions": "typing_extensions",
    "xlsxwriter": "xlsxwriter",
}


def main() -> None:
    exported = subprocess.check_output([
        "uv", "export", "--locked", "--only-group", "document-skills",
        "--no-header", "--no-annotate", "--no-hashes", "--no-emit-project",
    ], cwd=ROOT, text=True)
    environment = default_environment() | {
        "python_version": "3.12", "python_full_version": "3.12.13",
        "sys_platform": "darwin", "platform_system": "Darwin",
        "platform_machine": "arm64", "extra": "",
    }
    platforms = list(mac_platforms((13, 0), "arm64"))
    tags = list(cpython_tags((3, 12), platforms=platforms))
    tags.extend(compatible_tags((3, 12), interpreter="cp312", platforms=platforms))
    priority = {tag: index for index, tag in enumerate(tags)}
    packages = tomllib.loads((ROOT / "uv.lock").read_text())["package"]
    lines = ["# Generated by scripts/lock-document-dependencies.py from uv.lock."]
    imports = ["# Generated distribution-to-import mapping for the Skill bundle."]
    for line in exported.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        requirement = Requirement(line)
        if requirement.marker and not requirement.marker.evaluate(environment):
            continue
        name = canonicalize_name(requirement.name)
        version = next(iter(requirement.specifier)).version
        package = next(p for p in packages if p["name"] == name and p["version"] == version)
        wheels = []
        for wheel in package.get("wheels", []):
            filename = unquote(urlsplit(wheel["url"]).path.rsplit("/", 1)[-1])
            supported = parse_wheel_filename(filename)[3] & priority.keys()
            if supported:
                wheels.append((min(priority[tag] for tag in supported), wheel["hash"]))
        if not wheels:
            raise ValueError(f"No macOS 13 arm64 / CPython 3.12 wheel for {name}=={version}")
        digest = min(wheels)[1]
        lines.append(f"{name}=={version} --hash={digest} # import-name={IMPORTS[name]}")
        imports.append(f"{name}=={version}: {IMPORTS[name]}")
    destination = ROOT / "resources/runtime-dependencies/python"
    (destination / "requirements.lock").write_text("\n".join(lines) + "\n")
    (destination / "top_level.txt").write_text("\n".join(imports) + "\n")


if __name__ == "__main__":
    main()
