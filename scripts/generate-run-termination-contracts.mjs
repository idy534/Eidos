// Generate the Run termination DTO from its Python domain model.
import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.domain.run_termination import RunTermination
print(json.dumps(RunTermination.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
await writeFile(path.join(root, "desktop/shared/run-termination.generated.ts"), await compile(schema, "RunTermination", {
  bannerComment: "/* Generated by scripts/generate-run-termination-contracts.mjs. Do not edit. */",
  additionalProperties: false,
}));
