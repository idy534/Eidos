import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.protocol.channels import ChannelReadRequest, ChannelSaveRequest, ChannelResponse
from eidos_runtime.domain.channels import ChannelOrigin
class ChannelContract(EidosFrozenStrictModel):
    read: ChannelReadRequest
    save: ChannelSaveRequest
    response: ChannelResponse
    origin: ChannelOrigin
print(json.dumps(ChannelContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8", maxBuffer: 1024 * 1024 }));
const banner = "/* Generated by scripts/generate-channel-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/channels.generated.ts"), await compile(schema, "ChannelContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/channels-schema.generated.ts"), `${banner}\nexport const channelSchema = ${JSON.stringify(schema, null, 2)};\n`);
