import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.domain.plugins import PluginPresentation
print(json.dumps(PluginPresentation.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
const banner = "/* Generated by scripts/generate-plugin-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/plugins.generated.ts"), await compile(schema, "PluginPresentation", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/plugins-schema.generated.ts"), `${banner}\nexport const pluginPresentationSchema = ${JSON.stringify(schema, null, 2)};\n`);
