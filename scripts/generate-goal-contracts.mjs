import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models.base import EidosFrozenStrictModel
from eidos_runtime.protocol.goals import GoalRequest, GoalChangedNotice
from eidos_runtime.domain.goal import GoalView, GoalRunOrigin
class GoalContract(EidosFrozenStrictModel):
    request: GoalRequest
    response: GoalView
    notice: GoalChangedNotice
    origin: GoalRunOrigin
print(json.dumps(GoalContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
const banner = "/* Generated by scripts/generate-goal-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/goals.generated.ts"), await compile(schema, "GoalContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
const ajv = new Ajv2020({ strict: false, coerceTypes: false, inlineRefs: false, code: { source: true, esm: true, lines: true } });
ajv.addSchema(schema, "eidos:goals");
const definitions = { isGoalRequest: "GoalRequest", isGoalView: "GoalView", isGoalChangedNotice: "GoalChangedNotice", isGoalRunOrigin: "GoalRunOrigin" };
const generated = standaloneCode(ajv, Object.fromEntries(Object.entries(definitions).map(([name, definition]) => [name, `eidos:goals#/$defs/${definition}`])));
const browserCode = generated.replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2length");
if (/\brequire\(/u.test(browserCode)) throw new Error("Goal validators require an unsupported CommonJS helper.");
await writeFile(path.join(root, "desktop/shared/goals-validators.generated.ts"),
  `// @ts-nocheck -- Ajv standalone output; public types are declared in goals.ts.\n${banner}\nimport ucs2lengthRuntime from "ajv/dist/runtime/ucs2length.js";\nconst ucs2length = typeof ucs2lengthRuntime === "function" ? ucs2lengthRuntime : ucs2lengthRuntime.default;\n${browserCode.trimEnd()}\n`);
