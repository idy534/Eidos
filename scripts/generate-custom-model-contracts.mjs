import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.model.config import CustomModelSettings
from eidos_runtime.model.discovery import CustomProviderRequest, CustomProviderResult
class CustomModelContract(EidosFrozenStrictModel):
    settings: CustomModelSettings
    request: CustomProviderRequest
    result: CustomProviderResult
print(json.dumps(CustomModelContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
const banner = "/* Generated by scripts/generate-custom-model-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/custom-models.generated.ts"), await compile(schema, "CustomModelContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/custom-models-schema.generated.ts"), `${banner}\nexport const customModelSchema = ${JSON.stringify(schema, null, 2)};\n`);
const ajv = new Ajv2020({ strict: false, coerceTypes: false, inlineRefs: false, code: { source: true, esm: true, lines: true } });
ajv.addSchema(schema, "eidos:custom-models");
const generated = standaloneCode(ajv, {
  isCustomModelSettings: "eidos:custom-models#/$defs/CustomModelSettings",
  isCustomProviderResult: "eidos:custom-models#/$defs/CustomProviderResult",
});
const browserCode = generated.replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2length");
if (/\brequire\(/u.test(browserCode)) throw new Error("Unsupported CommonJS helper in custom model validators");
await writeFile(path.join(root, "desktop/shared/custom-models-validators.generated.ts"),
  `// @ts-nocheck -- Ajv standalone output; public types are declared in custom-models.ts.\n${banner}\nimport ucs2lengthRuntime from "ajv/dist/runtime/ucs2length.js";\nconst ucs2length = typeof ucs2lengthRuntime === "function" ? ucs2lengthRuntime : ucs2lengthRuntime.default;\n${browserCode.trimEnd()}\n`);
