// Generate search DTOs and their validators from the Python protocol schema.
import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.protocol.schemas import ClosedModel
from eidos_runtime.protocol.search import SearchResponse, SearchRequest, ReadAroundRequest, FileFindRequest, FileFindResponse
class SearchContract(ClosedModel):
    response: SearchResponse
    request: SearchRequest
    around: ReadAroundRequest
    file_find: FileFindRequest
    file_find_response: FileFindResponse
print(json.dumps(SearchContract.model_json_schema(by_alias=True)))
`], {
  cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") },
  encoding: "utf8", maxBuffer: 1024 * 1024,
}));
const banner = "/* Generated by scripts/generate-search-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/search.generated.ts"), await compile(schema, "SearchContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/search-schema.generated.ts"),
  `${banner}\nexport const searchSchema = ${JSON.stringify(schema, null, 2)};\n`);
