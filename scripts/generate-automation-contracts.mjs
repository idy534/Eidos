import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models.base import EidosFrozenStrictModel
from eidos_runtime.domain.automation import AutomationOrigin, AutomationResponse
from eidos_runtime.protocol.automations import AutomationExecuteRequest, AutomationHistoryRequest, AutomationRunNowRequest
class AutomationContract(EidosFrozenStrictModel):
    execute: AutomationExecuteRequest
    history: AutomationHistoryRequest
    run_now: AutomationRunNowRequest
    response: AutomationResponse
    origin: AutomationOrigin
print(json.dumps(AutomationContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8", maxBuffer: 1024 * 1024 }));
const banner = "/* Generated by scripts/generate-automation-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/automation.generated.ts"), await compile(schema, "AutomationContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/automation-schema.generated.ts"),
  `${banner}\nexport const automationSchema = ${JSON.stringify(schema, null, 2)};\n`);
