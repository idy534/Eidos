// Generate conversation fork DTOs and their validators from the Python protocol schema.
import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.protocol.schemas import ClosedModel
from eidos_runtime.protocol.session_fork import SessionForkResponse, SessionForkRequest
from eidos_runtime.protocol.schemas import InheritedHistoryEntry
from eidos_runtime.domain.session_fork import SessionForkSource
class SessionForkContract(ClosedModel):
    response: SessionForkResponse
    request: SessionForkRequest
    history: InheritedHistoryEntry
    source: SessionForkSource
print(json.dumps(SessionForkContract.model_json_schema(by_alias=True)))
`], {
  cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") },
  encoding: "utf8", maxBuffer: 1024 * 1024,
}));
for (const [name, type] of Object.entries({SessionDto: "Session", RunDto: "Run", ItemDto: "Item"})) {
  schema.$defs[name].tsType = `import("./domain-contracts.js").${type}`;
}
const banner = "/* Generated by scripts/generate-session-fork-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/session-fork.generated.ts"), await compile(schema, "SessionForkContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/session-fork-schema.generated.ts"),
  `${banner}\nexport const sessionForkSchema = ${JSON.stringify(schema, null, 2)};\n`);
