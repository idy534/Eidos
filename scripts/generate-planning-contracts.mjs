// Generate production DTOs from Python. This command does not run tests or start Runtime.
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { compile } from 'json-schema-to-typescript';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(execFileSync(path.join(root, '.venv/bin/python'), ['-c', `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.protocol.planning import PlanningReadResponse, AnswerInputRequest, PlanEditRequest, RunPlanningOptions
class PlanningContract(EidosFrozenStrictModel):
    state: PlanningReadResponse
    answer: AnswerInputRequest
    edit: PlanEditRequest
    run: RunPlanningOptions
print(json.dumps(PlanningContract.model_json_schema(by_alias=True)))
`], {cwd: root, env: {...process.env, PYTHONPATH: path.join(root, 'runtime')}, encoding: 'utf8', maxBuffer: 1024 * 1024}));
await writeFile(path.join(root, 'desktop/shared/planning.generated.ts'), await compile(schema, 'PlanningContract', {
  bannerComment: '/* Generated by scripts/generate-planning-contracts.mjs. Do not edit. */', additionalProperties: false, maxItems: -1,
}));
