import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.model.config import QoderModelSettings
from eidos_runtime.models.qoder import QoderConnectionRequest, QoderConnectionState
class QoderContract(EidosFrozenStrictModel):
    settings: QoderModelSettings
    request: QoderConnectionRequest
    result: QoderConnectionState
print(json.dumps(QoderContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
const banner = "/* Generated by scripts/generate-qoder-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/qoder.generated.ts"), await compile(schema, "QoderContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/qoder-schema.generated.ts"), `${banner}\nexport const qoderSchema = ${JSON.stringify(schema, null, 2)};\n`);
const ajv = new Ajv2020({ strict: false, coerceTypes: false, inlineRefs: false, code: { source: true, esm: true, lines: true } });
ajv.addSchema(schema, "eidos:qoder");
const generated = standaloneCode(ajv, {
  isQoderModelSettings: "eidos:qoder#/$defs/QoderModelSettings",
  isQoderConnectionRequest: "eidos:qoder#/$defs/QoderConnectionRequest",
  isQoderConnectionState: "eidos:qoder#/$defs/QoderConnectionState",
});
const browserCode = generated.replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2length");
if (/\brequire\(/u.test(browserCode)) throw new Error("Unsupported CommonJS helper in custom model validators");
await writeFile(path.join(root, "desktop/shared/qoder-validators.generated.ts"),
  `// @ts-nocheck -- Ajv standalone output; public types are declared in qoder.ts.\n${banner}\nimport ucs2lengthRuntime from "ajv/dist/runtime/ucs2length.js";\nconst ucs2length = typeof ucs2lengthRuntime === "function" ? ucs2lengthRuntime : ucs2lengthRuntime.default;\n${browserCode.trimEnd()}\n`);
