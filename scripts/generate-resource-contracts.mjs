import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.models.managed_resources import ResourceStatus, ResourceRetryRequest, ResourceRetryResponse, ResourceStatusRequest
class ManagedResourcesContract(EidosFrozenStrictModel):
    status_request: ResourceStatusRequest
    status: ResourceStatus
    retry: ResourceRetryRequest
    retry_response: ResourceRetryResponse
print(json.dumps(ManagedResourcesContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
const banner = "/* Generated by scripts/generate-resource-contracts.mjs. Do not edit. */";
const outputs = new Map([
  ["managed-resources.generated.ts", await compile(schema, "ManagedResourcesContract", {
    bannerComment: banner, additionalProperties: false, maxItems: -1,
  })],
  ["managed-resources-schema.generated.ts", `${banner}\nexport const managedResourcesSchema = ${JSON.stringify(schema, null, 2)};\n`],
]);
if (process.argv.slice(2).some(argument => argument !== "--check")) throw new Error("Only --check is supported");
for (const [name, content] of outputs) {
  const file = path.join(root, "desktop/shared", name);
  if (process.argv.includes("--check")) {
    if (await readFile(file, "utf8") !== content) throw new Error(`Generated resource contract is stale: ${name}`);
  } else await writeFile(file, content);
}
