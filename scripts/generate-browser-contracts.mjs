import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.models.browser import (
    BrowserCloseRequest, BrowserCloseResponse, BrowserGrantRevokeRequest,
    BrowserGrantRevokeResponse, BrowserStatus, BrowserStatusRequest,
)
class BrowserContract(EidosFrozenStrictModel):
    status_request: BrowserStatusRequest
    status: BrowserStatus
    revoke_request: BrowserGrantRevokeRequest
    revoke_response: BrowserGrantRevokeResponse
    close_request: BrowserCloseRequest
    close_response: BrowserCloseResponse
print(json.dumps(BrowserContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
const banner = "/* Generated by scripts/generate-browser-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/browser.generated.ts"), await compile(schema, "BrowserContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/browser-schema.generated.ts"), `${banner}\nexport const browserSchema = ${JSON.stringify(schema, null, 2)};\n`);
