import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { schema, methods } = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from pydantic import create_model
from eidos_runtime.models.base import EidosFrozenStrictModel
from eidos_runtime.domain.teams import TeamRunOrigin
from eidos_runtime.protocol.teams import TEAM_METHODS, TeamChangedNotice
models = {model.__name__: (model, ...) for _, request, response in TEAM_METHODS for model in (request, response)}
models["TeamRunOrigin"] = (TeamRunOrigin, ...)
models["TeamChangedNotice"] = (TeamChangedNotice, ...)
contract = create_model("TeamContract", __base__=EidosFrozenStrictModel, **models)
print(json.dumps({"schema": contract.model_json_schema(by_alias=True),
                  "methods": {method: [request.__name__, response.__name__] for method, request, response in TEAM_METHODS}}))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8", maxBuffer: 1024 * 1024 }));
const banner = "/* Generated by scripts/generate-team-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/teams.generated.ts"), await compile(schema, "TeamContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
const ajv = new Ajv2020({ strict: false, coerceTypes: false, inlineRefs: false, code: { source: true, esm: true, lines: true } });
ajv.addSchema(schema, "eidos:teams");
const models = [...new Set([...Object.values(methods).flat(), "TeamRunOrigin", "TeamChangedNotice"])];
const definitions = Object.fromEntries(models.map((model) => [`is${model}`, model]));
const generated = standaloneCode(ajv, Object.fromEntries(Object.entries(definitions).map(([name, definition]) => [name, `eidos:teams#/$defs/${definition}`])));
const browserCode = generated.replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2length");
if (/\brequire\(/u.test(browserCode)) throw new Error("Team validators require an unsupported CommonJS helper.");
await writeFile(path.join(root, "desktop/shared/teams-validators.generated.ts"),
  `// @ts-nocheck -- Ajv standalone output; public types are declared in teams.generated.ts.\n${banner}\nimport ucs2lengthRuntime from "ajv/dist/runtime/ucs2length.js";\nconst ucs2length = typeof ucs2lengthRuntime === "function" ? ucs2lengthRuntime : ucs2lengthRuntime.default;\n${browserCode.trimEnd()}\n`);
await writeFile(path.join(root, "desktop/shared/teams-methods.generated.ts"), `${banner}\nimport type * as DTO from "./teams.generated.js";\nexport interface TeamMethods {\n${Object.entries(methods).map(([method, [request, response]]) => `  "${method}": {request: DTO.${request}; response: DTO.${response}};`).join("\n")}\n}\nexport const teamMethodModels = ${JSON.stringify(methods, null, 2)} as const;\n`);
