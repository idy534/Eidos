import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.protocol.shell_environment import ShellEnvironmentReadRequest, ShellEnvironmentRefreshRequest, ShellEnvironmentSaveRequest, ShellEnvironmentResponse
class ShellEnvironmentContract(EidosFrozenStrictModel):
    read: ShellEnvironmentReadRequest
    refresh: ShellEnvironmentRefreshRequest
    save: ShellEnvironmentSaveRequest
    response: ShellEnvironmentResponse
print(json.dumps(ShellEnvironmentContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8", maxBuffer: 1024 * 1024 }));
const banner = "/* Generated by scripts/generate-shell-environment-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/shell-environment.generated.ts"), await compile(schema, "ShellEnvironmentContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/shell-environment-schema.generated.ts"), `${banner}\nexport const shellEnvironmentSchema = ${JSON.stringify(schema, null, 2)};\n`);
