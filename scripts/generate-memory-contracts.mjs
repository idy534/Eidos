import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const {schema, methods} = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from pydantic import create_model
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.application.memory import MEMORY_METHODS
models = {model.__name__: (model, ...) for _, request, response in MEMORY_METHODS for model in (request, response)}
contract = create_model("MemoryContract", __base__=EidosFrozenStrictModel, **models)
print(json.dumps({"schema": contract.model_json_schema(by_alias=True), "methods": {method: [request.__name__, response.__name__] for method, request, response in MEMORY_METHODS}}))
`], {cwd: root, env: {...process.env, PYTHONPATH: path.join(root, "runtime")}, encoding: "utf8", maxBuffer: 1024 * 1024}));
const banner = "/* Generated by scripts/generate-memory-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/memory.generated.ts"), await compile(schema, "MemoryContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/memory-schema.generated.ts"), `${banner}\nexport const memorySchema = ${JSON.stringify(schema, null, 2)};\nexport const memoryMethodModels = ${JSON.stringify(methods, null, 2)} as const;\n`);
await writeFile(path.join(root, "desktop/shared/memory-methods.generated.ts"), `${banner}\nimport type * as DTO from "./memory.generated.js";\nexport interface MemoryMethods {\n${Object.entries(methods).map(([method, [request, response]]) => `  "${method}": {request: DTO.${request}; response: DTO.${response}};`).join("\n")}\n}\n`);
