import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.protocol.personalization import PersonalizationReadRequest, PersonalizationSaveRequest, PersonalizationResponse
class PersonalizationContract(EidosFrozenStrictModel):
    read: PersonalizationReadRequest
    save: PersonalizationSaveRequest
    response: PersonalizationResponse
print(json.dumps(PersonalizationContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8", maxBuffer: 1024 * 1024 }));
const banner = "/* Generated by scripts/generate-personalization-contracts.mjs. Do not edit. */";
// The generator cannot represent if/then as a TypeScript type. Keep the
// cross-field constraint in the runtime JSON Schema and generate the fields.
const typeSchema = structuredClone(schema);
delete typeSchema.$defs.PersonalizationPreferences.allOf;
await writeFile(path.join(root, "desktop/shared/personalization.generated.ts"), await compile(typeSchema, "PersonalizationContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/personalization-schema.generated.ts"), `${banner}\nexport const personalizationSchema = ${JSON.stringify(schema, null, 2)};\n`);
