// Generate production DTOs from Python. This command does not run tests or start Runtime.
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { compile } from 'json-schema-to-typescript';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(execFileSync(path.join(root, '.venv/bin/python'), ['-c', `
import json
from eidos_runtime.models import EidosFrozenStrictModel
from eidos_runtime.domain.collaboration import CollaborationState
from eidos_runtime.domain.agents import AgentCatalogResponse
from eidos_runtime.protocol.collaboration import (AgentStopRequest, AgentDefinitionDocument, AgentDefinitionReadRequest, AgentDefinitionSaveRequest, AgentDefinitionRemoveRequest)
class CollaborationContract(EidosFrozenStrictModel):
    catalog: AgentCatalogResponse
    state: CollaborationState
    stop: AgentStopRequest
    definition: AgentDefinitionDocument
    definitionRead: AgentDefinitionReadRequest
    definitionSave: AgentDefinitionSaveRequest
    definitionRemove: AgentDefinitionRemoveRequest
print(json.dumps(CollaborationContract.model_json_schema(by_alias=True)))
`], {cwd: root, env: {...process.env, PYTHONPATH: path.join(root, 'runtime')}, encoding: 'utf8', maxBuffer: 1024 * 1024}));
await writeFile(path.join(root, 'desktop/shared/collaboration.generated.ts'), await compile(schema, 'CollaborationContract', {
  bannerComment: '/* Generated by scripts/generate-collaboration-contracts.mjs. Do not edit. */', additionalProperties: false, maxItems: -1,
}));
const definitions = ['AgentDefinition', 'AgentModelSelection', 'AgentDefinitionDocument', 'AgentDefinitionReadRequest', 'AgentDefinitionSaveRequest', 'AgentDefinitionRemoveRequest'];
await writeFile(path.join(root, 'desktop/shared/agent-definitions-schema.generated.ts'),
  '/* Generated by scripts/generate-collaboration-contracts.mjs. Do not edit. */\nexport const agentDefinitionsSchema = ' + JSON.stringify({$defs: Object.fromEntries(definitions.map(name => [name, schema.$defs[name]]))}, null, 2) + ' as const;\n');
