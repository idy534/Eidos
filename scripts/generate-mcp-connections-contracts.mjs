import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(execFileSync(path.join(root, ".venv/bin/python"), ["-c", `
import json
from eidos_runtime.models import EidosFrozenModel
from eidos_runtime.models.mcp_connections import McpConnectionRequest, McpConnectionState, BuiltinPluginRequest, BuiltinPluginsResponse, RemoteMcpInfo
class McpConnectionsContract(EidosFrozenModel):
    request: McpConnectionRequest
    response: McpConnectionState
    builtin_request: BuiltinPluginRequest
    builtin_response: BuiltinPluginsResponse
    remote_info: RemoteMcpInfo
print(json.dumps(McpConnectionsContract.model_json_schema(by_alias=True)))
`], { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, "runtime") }, encoding: "utf8" }));
const banner = "/* Generated by scripts/generate-mcp-connections-contracts.mjs. Do not edit. */";
await writeFile(path.join(root, "desktop/shared/mcp-connections.generated.ts"), await compile(schema, "McpConnectionsContract", {
  bannerComment: banner, additionalProperties: false, maxItems: -1,
}));
await writeFile(path.join(root, "desktop/shared/mcp-connections-schema.generated.ts"), `${banner}\nexport const mcpConnectionsSchema = ${JSON.stringify(schema, null, 2)};\n`);
